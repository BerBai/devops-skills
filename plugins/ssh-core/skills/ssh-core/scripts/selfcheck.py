#!/usr/bin/env python3
"""selfcheck.py - answer "what can this machine actually do?" in one command.

``SKILL.md`` opens with prerequisites and then a matrix of optional features
(paramiko, rsync, scp, ``ssh-copy-id``, ControlMaster, a pty ...). Asking a
user to read that and infer which half of the skill works on *their* box is a
guessing game. This script removes the guesswork (DV-02).

It is deliberately dependency-free: the standard library and whatever the
system already has. Nothing here imports paramiko, because installing paramiko
in order to discover whether paramiko is installed is circular.

Usage::

    python scripts/selfcheck.py                 # human table
    python scripts/selfcheck.py --json          # shared JSON envelope
    python scripts/selfcheck.py --check paramiko --check rsync
                                                # exit 9 if any is unusable
    python scripts/selfcheck.py --write-matrix references/platform-matrix.md
                                                # regenerate the doc (DV-26)

Scope note (OPT-001): this script answers "which binaries exist on *this*
machine" and deliberately stops there. It does not probe the backends of the
other plugins in the marketplace (``docker``/``podman``, ``kubectl``/``helm``,
``terraform``/``tofu``, ``gh``/``glab``, ``yaml``/``hcl2``), because that answer
depends on the *target*, needs a real ssh round trip, and would put a network
call behind a command documented as dependency-free. The report therefore ends
with a pointer to ``doctor.py --profile full [--host ALIAS]`` (and carries the
same string in ``data.profile_hint``) instead of growing a second, divergent
implementation of the same probe.

Exit codes: ``0`` everything required is present (optional gaps are reported,
not fatal), ``9`` when a ``--check`` target is missing, ``2`` argv error.
``--strict`` turns "no optional transfer backend at all" into exit 9 so CI can
catch a slim image that silently lost file transfer.

See ``references/platform-matrix.md`` (generated by ``--write-matrix``) for the
capability matrix that every other document links to instead of restating.
"""

from __future__ import annotations

import argparse  # noqa: F401  (kept for the public `selfcheck.argparse` surface)
import json
import platform
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

# Keep the tree free of __pycache__/*.pyc: a plain `python3 <script>` would
# otherwise write bytecode into the installed (verified) skill directory.
# Must run before `import lib` below. No-op for behaviour.
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).parent))
from lib import CHILD_TEXT_KWARGS, msys_safe_env  # noqa: E402
from lib.cli import SSHArgumentParser, guarded_main, handle_version  # noqa: E402
from lib.exit_codes import (  # noqa: E402
    EXIT_INTERNAL,
    EXIT_INVALID_ARGUMENTS,
    EXIT_OK,
    EXIT_VERIFY_FAILED,
)
from lib.transfer import have, paramiko_available  # noqa: E402
from lib.version import VERSION_LINE, __version__  # noqa: E402

SCRIPTS_DIR = Path(__file__).resolve().parent
SKILL_DIR = SCRIPTS_DIR.parent

#: Every script that must answer ``--version`` and ``--help`` (DV-11).
#:
#: FA-20: this list used to stop at the ten remote scripts, so the report said
#: ``10/10`` while there were twelve scripts answering ``--version``. The two
#: local-only tools are included now — a script that cannot report its version
#: is a script nobody can support.
SCRIPT_FILES: tuple[str, ...] = (
    "ssh_execute.py",
    "ssh_session.py",
    "ssh_cluster.py",
    "ssh_daemon.py",
    "ssh_tunnel.py",
    "ssh_upload.py",
    "ssh_download.py",
    "ssh_server_transfer.py",
    "ssh_slice.py",
    "deploy_pubkey.py",
    "ssh_config_manager.py",
    "audit.py",
    "selfcheck.py",
    "doctor.py",
)

#: Optional capabilities and what disappears when they are missing.
CAPABILITY_NOTES: dict[str, str] = {
    "paramiko": "SFTP resume/chmod/bwlimit/progress and `stream` server transfer",
    "rsync": "`ssh_server_transfer --use-rsync` (incremental copies)",
    "scp": "file transfer on hosts without paramiko",
    "ssh-copy-id": "nothing: deploy_pubkey installs the key itself",
    "ssh-keygen": "key inspection / known_hosts maintenance",
    "tar": "recursive transfer fallbacks (tar streams)",
    "sftp": "native sftp(1) debugging only; ssh-core uses paramiko or scp",
}

#: ``--check`` aliases so a caller can ask for a feature, not a binary.
CHECK_ALIASES: dict[str, str] = {
    "sftp": "paramiko",
    "transfer": "paramiko",
    "rsync": "rsync",
    "scp": "scp",
    "paramiko": "paramiko",
    "ssh": "ssh",
    "ssh-copy-id": "ssh-copy-id",
    "ssh-keygen": "ssh-keygen",
    "tar": "tar",
}

#: Where the cross-plugin answer lives (OPT-001). selfcheck stays a local,
#: dependency-free probe; the marketplace-wide readiness report (docker /
#: kubectl / terraform / gh / yaml / hcl2, optionally against a target) is
#: `doctor.py --profile full`. Repeating the probe here would mean two
#: implementations that disagree about the same binaries.
PROFILE_HINT = (
    "other plugins' backends (docker/kubectl/terraform/gh/hcl2/yaml) are not "
    "probed here; run `doctor.py --profile full [--host ALIAS]` for the "
    "per-plugin readiness report"
)


@dataclass
class CheckResult:
    """One row of the self-check table."""

    name: str
    value: str
    status: str  # "ok" | "missing" | "degraded" | "warn"
    note: str = ""
    required: bool = False

    @property
    def ok(self) -> bool:
        return self.status == "ok"

    def as_dict(self) -> dict[str, object]:
        return {
            "name": self.name,
            "value": self.value,
            "status": self.status,
            "note": self.note,
            "required": self.required,
        }


@dataclass
class SelfCheck:
    """The whole picture: environment, tools, capabilities, scripts."""

    checks: list[CheckResult] = field(default_factory=list)
    capabilities: dict[str, bool] = field(default_factory=dict)

    def add(self, result: CheckResult) -> None:
        self.checks.append(result)

    def as_dict(self) -> dict[str, object]:
        return {
            "version": __version__,
            "platform": platform.platform(),
            "python": platform.python_version(),
            "executable": sys.executable,
            "checks": [c.as_dict() for c in self.checks],
            "capabilities": self.capabilities,
            # OPT-001: where the cross-plugin answer lives. A pointer, not a
            # second implementation — see PROFILE_HINT.
            "profile_hint": PROFILE_HINT,
        }


def _tool_version(program: str, args: list[str] | None = None) -> str:
    """First line of ``<program> <args>``, or "" when it cannot be run."""
    argv = [program, *(args or ["--version"])]
    try:
        proc = subprocess.run(
            argv, capture_output=True, text=True, timeout=10, check=False,
            env=msys_safe_env(), **CHILD_TEXT_KWARGS,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    text = (proc.stdout or proc.stderr or "").strip()
    return text.splitlines()[0].strip() if text else ""


def _check_ssh(check: SelfCheck) -> bool:
    path = shutil.which("ssh")
    if not path:
        check.add(CheckResult(
            "ssh", "missing", "missing",
            "OpenSSH client not on PATH; every remote route needs it",
            required=True,
        ))
        return False
    version = _tool_version("ssh", ["-V"])
    check.add(CheckResult("ssh", path, "ok", version))
    return True


def _check_tools(check: SelfCheck) -> None:
    for tool, status_when_missing in (
        ("scp", "warn"),
        ("ssh-keygen", "warn"),
        ("ssh-copy-id", "warn"),
        ("rsync", "warn"),
        ("tar", "degraded"),
        ("sftp", "warn"),
    ):
        path = shutil.which(tool)
        if path:
            check.add(CheckResult(tool, path, "ok", ""))
        else:
            note = CAPABILITY_NOTES.get(tool, "")
            check.add(CheckResult(
                tool, "missing", status_when_missing,
                f"-> {note}" if note else "",
            ))


def _check_paramiko(check: SelfCheck) -> bool:
    if paramiko_available():
        try:
            import paramiko  # noqa: F401

            version = getattr(paramiko, "__version__", "unknown")
        except Exception:  # noqa: BLE001
            version = "unknown"
        check.add(CheckResult("paramiko", version, "ok", "SFTP backend available"))
        return True
    check.add(CheckResult(
        "paramiko", "missing", "degraded",
        "-> SFTP resume/bwlimit/progress and `stream` transfer fall back to "
        "scp/tar; install with: pip install 'paramiko>=3.0,<4'",
    ))
    return False


def _check_ssh_config(check: SelfCheck) -> None:
    path = Path("~/.ssh/config").expanduser()
    if not path.exists():
        check.add(CheckResult(
            "~/.ssh/config", "absent", "warn",
            "no host aliases yet; ad-hoc user@host still works and "
            "`ssh_config_manager.py create` makes the file",
        ))
        return
    try:
        with path.open("rb") as handle:
            handle.read(1)
    except OSError as exc:
        check.add(CheckResult("~/.ssh/config", "unreadable", "warn", str(exc)))
        return
    check.add(CheckResult("~/.ssh/config", str(path), "ok", ""))


def _check_scripts(check: SelfCheck) -> int:
    """Run ``--version`` on every script; returns how many answered."""
    answered = 0
    failures: list[str] = []
    for name in SCRIPT_FILES:
        path = SCRIPTS_DIR / name
        if not path.is_file():
            failures.append(f"{name}: missing")
            continue
        try:
            proc = subprocess.run(
                [sys.executable, str(path), "--version"],
                capture_output=True, text=True, timeout=30, check=False,
                env=msys_safe_env(), **CHILD_TEXT_KWARGS,
            )
        except (OSError, subprocess.SubprocessError) as exc:
            failures.append(f"{name}: {exc}")
            continue
        out = (proc.stdout or "").strip()
        if proc.returncode == 0 and __version__ in out:
            answered += 1
        else:
            failures.append(f"{name}: rc={proc.returncode} {out!r}")
    total = len(SCRIPT_FILES)
    if answered == total:
        check.add(CheckResult("script --version", f"{answered}/{total}", "ok", ""))
    else:
        check.add(CheckResult(
            "script --version", f"{answered}/{total}", "degraded",
            "; ".join(failures),
            required=True,
        ))
    return answered


def build() -> SelfCheck:
    """Probe the machine and return the full picture."""
    check = SelfCheck()
    check.add(CheckResult(
        "python", platform.python_version(), "ok", sys.executable,
        required=True,
    ))
    check.add(CheckResult(
        "platform", f"{platform.system()} {platform.release()}", "ok",
        f"machine={platform.machine()}",
    ))

    has_ssh = _check_ssh(check)
    _check_tools(check)
    has_paramiko = _check_paramiko(check)
    _check_ssh_config(check)
    answered = _check_scripts(check)

    has_scp = have("scp")
    has_rsync = have("rsync")
    has_tar = have("tar")
    has_copy_id = have("ssh-copy-id")
    from lib.platform import supports_pty_session

    pty_ok = supports_pty_session()
    posix = not sys.platform.startswith("win")

    check.capabilities = {
        # Exec / session / cluster / tunnel / config: stdlib + ssh only.
        "exec": has_ssh,
        "session_pty": has_ssh and pty_ok,
        "session_pipe": has_ssh,
        "cluster": has_ssh and answered > 0,
        "tunnel": has_ssh,
        "daemon": has_ssh,
        "config_manager": True,
        "deploy_pubkey_key": has_ssh,
        "deploy_pubkey_password": has_ssh,
        "transfer_sftp": has_paramiko,
        "transfer_scp": has_scp,
        "transfer_tar": has_tar,
        "server_transfer_stream": has_paramiko,
        "server_transfer_direct": has_ssh and has_tar,
        "server_transfer_rsync": has_rsync,
        "audit": True,
        "inventory_export": True,
        "sudo": has_ssh,
        "follow": has_ssh,
        "control_master": posix,
        "ssh_copy_id": has_copy_id,
    }
    return check


def _fmt_row(check: CheckResult, name_width: int) -> str:
    marker = {
        "ok": "OK",
        "missing": "MISSING",
        "degraded": "DEGRADED",
        "warn": "optional",
    }.get(check.status, check.status.upper())
    line = f"  {check.name:<{name_width}} {check.value:<28} {marker}"
    if check.note:
        line += f"   {check.note}"
    return line.rstrip()


def render_human(check: SelfCheck) -> str:
    name_width = max(len(c.name) for c in check.checks) + 2
    lines = [f"ssh-core selfcheck  ({VERSION_LINE})", ""]
    for result in check.checks:
        lines.append(_fmt_row(result, name_width))

    usable = sorted(k for k, v in check.capabilities.items() if v)
    missing = sorted(k for k, v in check.capabilities.items() if not v)
    lines.append("")
    lines.append("  available: " + (", ".join(usable) or "(none)"))
    if missing:
        lines.append("  unavailable: " + ", ".join(missing))
    lines.append("")
    lines.append(
        "  Note: `unavailable` entries are optional backends; exec / session / "
        "tunnel / config work with ssh alone."
    )
    lines.append("  " + PROFILE_HINT)
    return "\n".join(lines) + "\n"


def _missing_targets(wanted: list[str]) -> list[str]:
    missing: list[str] = []
    for name in wanted:
        target = CHECK_ALIASES.get(name, name)
        if target == "paramiko":
            if not paramiko_available():
                missing.append(name)
        elif not have(target):
            missing.append(name)
    return missing


def _exit_code(check: SelfCheck, wanted: list[str], strict: bool) -> int:
    if wanted:
        return EXIT_VERIFY_FAILED if _missing_targets(wanted) else EXIT_OK
    if any(c.required and not c.ok for c in check.checks):
        return EXIT_VERIFY_FAILED
    if strict:
        transfer = (
            check.capabilities.get("transfer_sftp")
            or check.capabilities.get("transfer_scp")
            or check.capabilities.get("transfer_tar")
        )
        if not transfer:
            return EXIT_VERIFY_FAILED
    return EXIT_OK


def matrix_markdown(check: SelfCheck) -> str:
    """Render ``references/platform-matrix.md`` from live probe data (DV-26).

    This is the single source for "what works where". Every other document
    links here instead of restating the table, so a capability change is one
    edit (the generator) rather than three that disagree.
    """
    cap_labels = {
        "exec": ("Command execution (`ssh_execute`)", "ssh"),
        "session_pty": ("Interactive device session over a pty", "ssh + pty"),
        "session_pipe": ("Interactive device session over pipes", "ssh"),
        "cluster": ("Fleet broadcast (`ssh_cluster`)", "ssh + ssh_execute"),
        "tunnel": ("Port forwards `-L`/`-R`/`-D` (`ssh_tunnel`)", "ssh"),
        "daemon": ("Session daemon (`ssh_daemon`)", "ssh"),
        "config_manager": ("`~/.ssh/config` CRUD + restore", "stdlib"),
        "deploy_pubkey_key": ("`deploy_pubkey` (key route)", "ssh"),
        "deploy_pubkey_password": ("`deploy_pubkey --password`", "ssh"),
        "transfer_sftp": (
            "SFTP transfer (`--resume`, `--bwlimit`, `--chmod`, `--preserve`)",
            "paramiko",
        ),
        "transfer_scp": ("scp transfer fallback", "scp"),
        "transfer_tar": ("tar stream transfer fallback", "tar"),
        "server_transfer_stream": ("`ssh_server_transfer --mode stream`", "paramiko"),
        "server_transfer_direct": ("`ssh_server_transfer --mode direct`", "ssh + tar"),
        "server_transfer_rsync": ("`ssh_server_transfer --use-rsync`", "rsync"),
        "audit": ("Audit trail (`--audit-log`) + rotation", "stdlib"),
        "inventory_export": ("`ssh_config_manager list --format`", "stdlib"),
        "sudo": ("Privilege escalation (`--sudo`)", "ssh + sudoers"),
        "follow": ("Log following (`--follow`/`--tail`)", "ssh"),
        "control_master": ("OpenSSH `ControlMaster` reuse", "POSIX socket"),
        "ssh_copy_id": ("`ssh-copy-id` (not required by ssh-core)", "ssh-copy-id"),
    }
    lines = [
        "# Platform capability matrix",
        "",
        "<!--",
        "Generated by scripts/selfcheck.py --write-matrix. Do not edit by hand:",
        "change the probe in selfcheck.py and regenerate, otherwise this table",
        "and reality drift apart (DV-26).",
        "-->",
        "",
        f"Generated on `{platform.platform()}` with Python "
        f"{platform.python_version()} for **{VERSION_LINE}**.",
        "",
        "## This machine",
        "",
        "| Capability | Available | Needs |",
        "|---|---|---|",
    ]
    for key, (label, needs) in cap_labels.items():
        available = check.capabilities.get(key)
        mark = "yes" if available else "**no**"
        lines.append(f"| {label} | {mark} | {needs} |")

    lines += [
        "",
        "## By platform",
        "",
        "These are the *designed* answers; the table above is what this host",
        "actually reports. Anything a script cannot do, it refuses with a",
        "`failure_class` and a remediation message rather than failing obscurely.",
        "",
        "| Capability | Linux | macOS | Windows |",
        "|---|---|---|---|",
        "| Command execution (key auth) | yes | yes | yes |",
        "| Command execution (password auth) | yes (`SSH_ASKPASS`, no pty "
        "needed) | yes (`SSH_ASKPASS` or pty) | yes (`SSH_ASKPASS` over an "
        "exec channel) |",
        "| Interactive device sessions | yes | yes | yes (pipe transport) |",
        "| Fleet broadcast | yes | yes | yes |",
        "| Port forwards `-L`/`-R`/`-D` | yes | yes | yes |",
        "| SFTP backend | paramiko | paramiko | paramiko |",
        "| scp / tar fallback | yes | yes | yes |",
        "| rsync server-to-server | if rsync installed | if rsync installed | "
        "needs rsync (Git/MSYS) |",
        "| `deploy_pubkey` | yes | yes | yes (no `ssh-copy-id` needed) |",
        "| `~/.ssh/config` CRUD | yes | yes | yes |",
        "| `--control-master auto` | yes | yes | **no** (POSIX socket), use "
        "`--commands-file` |",
        "| `--sudo` | yes | yes | yes (the remote side decides) |",
        "| `--follow` / `--tail` | yes | yes | yes |",
        "| Audit trail / rotation | yes | yes | yes |",
        "| TCP `--probe` | yes | yes | yes |",
        "| `ssh_daemon` | yes | yes | yes |",
        "| `ssh_slice` (windowed reads + cursor) | yes | yes | yes |",
        "| `doctor` (live capability probes) | yes | yes | yes |",
        "",
        "### Windows specifics",
        "",
        "- Password auth answers OpenSSH's prompt with a temporary",
        "  `SSH_ASKPASS` helper over a normal **exec** channel — no pty, no",
        "  `-tt`, so stdout/stderr stay separate and the remote exit code is",
        "  real. The helper lives in a private directory (`SSH_CORE_ASKPASS_DIR`",
        "  overrides it) that is tightened with `icacls`, because",
        "  `mkdir(mode=0o700)` can produce a DACL without the creating user.",
        "- `--control-master auto` is refused with `dependency_missing` and points",
        "  at `--commands-file` / `ssh_daemon.py`, which give the same",
        "  one-handshake benefit without a POSIX socket.",
        "- There is usually no `python` on `PATH` inside a DSH install:",
        "  `scripts\\run.cmd <script.py> ...` resolves `$SSH_CORE_PYTHON`,",
        "  `$DSH_PYTHON`, `python`/`py -3` and the bundled runtime, in that order.",
        "- Process liveness uses `OpenProcess` + `GetExitCodeProcess`, never",
        "  `os.kill(pid, 0)` (which would *terminate* the process on Windows).",
        "- The `local` route starts a real process, so only an `.exe`/`.cmd`/`.bat`",
        "  on `PATH` works directly. `cmd.exe` builtins (`echo`, `dir`, `copy`,",
        "  `set`, \u2026) and PowerShell cmdlets need `cmd /c ...` /",
        "  `powershell -Command ...` or `--shell cmd|powershell`; `bash` is not",
        "  assumed to exist. The native tail/read paths and `port_check.py`",
        "  probes need no shell at all.",
        "",
        "### Python",
        "",
        "Everything targets Python 3.8+ so older enterprise hosts (Kylin 3,",
        "CentOS 7 with EPEL) keep working; the CI matrix covers 3.8 / 3.10 /",
        "3.12, and `tools/check_python_floor.py` enforces the floor against",
        "the code (including `write_text(newline=)` and",
        "`TemporaryDirectory(ignore_cleanup_errors=)`, both 3.10+).",
        "",
        "### Verifying a machine",
        "",
        "`selfcheck.py` reports which binaries exist; `doctor.py` runs the",
        "capability (a staged askpass helper, a real login, a real upload and",
        "download with a sha256 check, an optional `sudo -n` probe) so a green",
        "line means the operation works, not that the tool is installed.",
        "`doctor.py --require NAME` exits 9 when a required capability regressed.",
        "",
    ]
    return "\n".join(lines)


def _emit(payload: dict, as_json: bool) -> None:
    if as_json:
        json.dump(payload, sys.stdout, ensure_ascii=False)
        sys.stdout.write("\n")
    else:
        sys.stdout.write(payload.get("stdout") or "")
        if payload.get("stderr"):
            sys.stderr.write(payload["stderr"])


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    early = handle_version("selfcheck.py", argv)
    if early is not None:
        return early

    parser = SSHArgumentParser(
        prog="selfcheck.py",
        description=(
            "Report which ssh-core capabilities work on this machine, "
            "dependency-free. Exits 0 when everything required is present."
        ),
    )
    parser.add_argument(
        "--check", action="append", default=[], metavar="NAME",
        help=(
            "Fail (exit 9) unless this tool/capability is usable; repeatable. "
            f"Known names: {', '.join(sorted(CHECK_ALIASES))}"
        ),
    )
    parser.add_argument(
        "--strict", action="store_true",
        help="Also fail when no file-transfer backend at all is available",
    )
    parser.add_argument(
        "--write-matrix", default=None, metavar="PATH",
        help=(
            "Write references/platform-matrix.md (regenerated from this probe) "
            "instead of printing the table (DV-26)"
        ),
    )
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--version", "-V", action="store_true")
    args = parser.parse_args(argv)

    try:
        check = build()
    except Exception as exc:  # noqa: BLE001 - a self-check must never traceback
        _emit(
            {
                "success": False,
                "exit_code": EXIT_INTERNAL,
                "stdout": "",
                "stderr": f"selfcheck: internal error: {type(exc).__name__}: {exc}\n",
                "data": {"failure_class": "internal"},
            },
            args.json,
        )
        return EXIT_INTERNAL

    code = _exit_code(check, args.check, args.strict)
    missing = _missing_targets(args.check) if args.check else []

    if args.write_matrix:
        target = Path(args.write_matrix).expanduser()
        try:
            target.parent.mkdir(parents=True, exist_ok=True)
            # newline="\n": the generated doc must stay LF on Windows too, or
            # `.gitattributes` and CI's line-ending gate both trip.
            with target.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(matrix_markdown(check))
        except OSError as exc:
            _emit(
                {
                    "success": False,
                    "exit_code": EXIT_INVALID_ARGUMENTS,
                    "stdout": "",
                    "stderr": f"selfcheck: cannot write {target}: {exc}\n",
                    "data": {"failure_class": "invalid_arguments"},
                },
                args.json,
            )
            return EXIT_INVALID_ARGUMENTS
        _emit(
            {
                "success": code == EXIT_OK,
                "exit_code": code,
                "stdout": "",
                "stderr": f"selfcheck: wrote {target}\n",
                "data": {
                    "written": str(target),
                    "failure_class": None if code == EXIT_OK else "verify_failed",
                    "missing": missing,
                    **check.as_dict(),
                },
            },
            args.json,
        )
        return code

    payload = {
        "success": code == EXIT_OK,
        "exit_code": code,
        "stdout": "" if args.json else render_human(check),
        "stderr": (
            f"selfcheck: missing: {', '.join(missing)}\n" if missing else ""
        ),
        "data": {
            "failure_class": None if code == EXIT_OK else "verify_failed",
            "missing": missing,
            **check.as_dict(),
        },
    }
    _emit(payload, args.json)
    return code


